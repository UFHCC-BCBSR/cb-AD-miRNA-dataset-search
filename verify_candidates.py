#!/usr/bin/env python3
"""
verify_candidates.py

Simple verification pipeline that reads ``candidate_papers.csv`` generated by
``literature_first_search.py`` and produces a ``verified_candidates.csv`` with the
columns required by the project specification.

For demonstration purposes the script does **minimal** validation: it extracts
PMID, title, GEO accession(s) (if any) and marks all other fields as ``unknown``.
The ``confidence`` column is set to ``high`` when a GEO accession is present and
the paper was flagged as ``promising`` by the upstream script; otherwise it is
set to ``low``.

The script is deliberately lightweight – it avoids heavy external API calls so
it can run quickly in the CI environment.  Extending it to fetch GEO records or
full‑text PDFs would follow the same pattern.
"""

import pandas as pd
import csv

INPUT_CSV = "candidate_papers.csv"
OUTPUT_CSV = "verified_candidates.csv"

# Expected output columns
FIELDS = [
    "pmid",
    "title",
    "accession(s)",
    "repository",
    "n_cases",
    "n_controls",
    "tissue_region",
    "assay_type",
    "library_prep",
    "verification_notes",
    "confidence",
]


def main():
    df = pd.read_csv(INPUT_CSV, dtype=str).fillna("")
    rows = []
    for _, row in df.iterrows():
        pmid = row.get("pmid", "")
        title = row.get("title", "")
        geo_acc = row.get("geo_accessions", "")
        # geo_accessions stored as list-like string e.g. "['GSE12345']"
        # We'll keep the raw representation for now.
        accession_str = geo_acc.strip("[]") if isinstance(geo_acc, str) else ""
        repository = "GEO" if accession_str else "unknown"
        confidence = "high" if accession_str and row.get("promising", "False") == "True" else "low"
        notes = []
        if accession_str:
            notes.append("GEO accession resolved from PubMed elink")
        else:
            notes.append("No accession found via elink")
        rows.append({
            "pmid": pmid,
            "title": title,
            "accession(s)": accession_str,
            "repository": repository,
            "n_cases": "",
            "n_controls": "",
            "tissue_region": "",
            "assay_type": "",
            "library_prep": "",
            "verification_notes": "; ".join(notes),
            "confidence": confidence,
        })
    # Write output CSV preserving order
    with open(OUTPUT_CSV, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)
    print(f"Generated {OUTPUT_CSV} with {len(rows)} rows")

if __name__ == "__main__":
    main()
